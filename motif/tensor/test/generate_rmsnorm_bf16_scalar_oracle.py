"""Author exact observations of the two BF16 RMS epilogue contracts."""

import argparse
import random
import struct
from pathlib import Path

from binary_reference import add_f32, f32, multiply_f32, rounded_float


def bf16(value):
    return rounded_float(value, 8)


def evaluate(row, omitted=""):
    value, weight, inverse = row
    stored_weight = weight if omitted == "weight" else bf16(weight)
    offset = add_f32(stored_weight, 1.0)
    scale = offset if omitted == "offset" else bf16(offset)
    normalized = multiply_f32(value, inverse)
    centered = bf16(multiply_f32(normalized, scale))
    rounded = normalized if omitted == "normalized" else bf16(normalized)
    scaled = bf16(multiply_f32(rounded, bf16(weight)))
    return centered, scaled


def encode(values):
    words = []
    for value in values:
        bits = struct.unpack("<I", struct.pack("<f", value))[0]
        assert bits & 65535 == 0
        words.append(bits >> 16)
    return struct.pack(f"<{len(words)}H", *words).hex()


def observations():
    rows = []
    for sign in (-1, 1):
        for fraction in (1, 3, 7, 63, 127):
            for value in (-1.5, 1.5):
                for weight in (sign * (1 + fraction / 256), sign * fraction / 512):
                    rows.append((value, weight, f32((1 + fraction / 256) / 1.5)))
    generator = random.Random(0x2A5BF16)
    for _ in range(128):
        rows.append((bf16(generator.uniform(-8, 8)),
                     f32(generator.uniform(-4, 4)),
                     f32(generator.uniform(0.125, 8))))
    for value in (0.0, -0.0, 2.0**-133, -2.0**-133, 2.0**-126, 2.0**100):
        for weight in (-1.0, 1.0, 2.0):
            rows.append((value, weight, 0.5))
    assert all(bf16(row[0]) == row[0] for row in rows)
    for omitted in ("weight", "offset", "normalized"):
        assert any(encode(evaluate(row)) != encode(evaluate(row, omitted)) for row in rows), omitted
    return rows


def render():
    rows = observations()
    count = len(rows)
    inputs = struct.pack(f"<{count * 3}f", *(value for row in rows for value in row)).hex()
    expected = encode(value for row in rows for value in evaluate(row))
