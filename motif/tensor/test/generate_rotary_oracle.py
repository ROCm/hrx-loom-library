@dataclass(frozen=True)
class Shape:
    # Stable observation name.
    name: str
    # Positions indexing independent coefficient rows.
    tokens: int
    # Heads sharing each token's coefficient row.
    heads: int
    # Channels in one head; each thread owns a pair.
    width: int
    # Independently authored input/table distribution.
    pattern: str = "dyadic"
    # Whether output occupies exactly the input allocation.
    inplace: bool = False


SHAPES = (
    Shape("unit", 1, 1, 64, "unit"),
    Shape("partial_wave", 2, 3, 96),
    Shape("token_heads", 3, 2, 128),
    Shape("wide", 2, 2, 256),
    Shape("inplace", 2, 3, 128, inplace=True),
    Shape("zero", 1, 2, 64, "zero"),
)


def epsilon_for(shape, kind):
    if shape.pattern == "unit":
        return 0.0
    if shape.name == "wide":
        return 0.125
    return f32(1e-5 if kind == "adjacent" else 1e-6)


def inverse_endpoints(inverse):
    endpoints = []
    for direction in (-1, 1):
        exact = inverse * (1 + direction * 2.0**-16)
        value = f32(exact)
        if (value - exact) * direction < 0:
            bits = struct.unpack("<I", struct.pack("<f", value))[0] + direction
            value = struct.unpack("<f", struct.pack("<I", bits))[0]
        endpoints.append(value)
    return endpoints


def normalized(value, weight, inverse, kind):
    if kind == "adjacent":
        scale = bf16(add_f32(bf16(weight), 1.0))
        return bf16(multiply_f32(multiply_f32(value, inverse), scale))
    return bf16(multiply_f32(bf16(multiply_f32(value, inverse)), weight))


def row_observations(shape, kind):
    rows = shape.tokens * shape.heads
    choices = (-2.0, -1.0, -0.5, -0.25, 0.25, 0.5, 1.0, 2.0)
    inputs = []
    for row in range(rows):
        for column in range(shape.width):
            value = choices[(row * 7 + column * 11) % len(choices)]
            if shape.pattern == "unit":
                value = math.copysign(1.0, value)
            elif shape.pattern == "zero":
                value = math.copysign(0.0, value)
            inputs.append(value)
    scales = (-1.5, -0.75, -0.25, 0.25, 0.75, 1.5)
    weights = [scales[(column * 5) % len(scales)] for column in range(shape.width)]
    if kind == "adjacent":
        weights = [f32(weight + 2.0**-10) for weight in weights]
    coefficients = []
    for sine in (False, True):
        values = []
        for token in range(shape.tokens):
            for column in range(shape.width):
                value = math.sin((token + 2) * (column + 5) / 23) if sine else math.cos((token + 1) * (column + 3) / 17)
                if shape.pattern == "unit":
                    value = (0.0, 0.5, 1.0, -0.5, -1.0)[(column + int(sine)) % 5]
                values.append(f32(value) if kind == "adjacent" else bf16(value))
        coefficients.append(values)
    cosine, sine = coefficients
    expected = []
    for row in range(rows):
        values = inputs[row * shape.width:(row + 1) * shape.width]
        if kind != "half":
            inverse = 1.0 / math.sqrt(math.fsum(value * value for value in values) / shape.width + epsilon_for(shape, kind))
            lower, upper = inverse_endpoints(inverse)
            low_values = [normalized(value, weight, lower, kind) for value, weight in zip(values, weights)]
            high_values = [normalized(value, weight, upper, kind) for value, weight in zip(values, weights)]
            assert encode(low_values) == encode(high_values), (shape.name, kind, row, "normalization boundary")
            values = low_values
        token_origin = (row // shape.heads) * shape.width
        result = [None] * shape.width
        pairs = ((column, column + 1) for column in range(0, shape.width, 2)) if kind == "adjacent" else ((column, column + shape.width // 2) for column in range(shape.width // 2))
        for left, right in pairs:
            left_cosine, right_cosine = cosine[token_origin + left], cosine[token_origin + right]
            left_sine, right_sine = sine[token_origin + left], sine[token_origin + right]
            if kind == "adjacent":
                result[left] = bf16(add_f32(multiply_f32(values[left], left_cosine), -multiply_f32(values[right], left_sine)))
                result[right] = bf16(add_f32(multiply_f32(values[right], right_cosine), multiply_f32(values[left], right_sine)))
            else:
                result[left], result[right] = half_pair((values[left], values[right], left_cosine, right_cosine, left_sine, right_sine))
        expected.extend(result)
    return inputs, weights, cosine, sine, expected


def render_row(shape, kind):
    name = f"{kind}_{shape.name}"
    inputs, weights, cosine, sine, expected = row_observations(shape, kind)
    count = len(inputs)
    table_count = len(cosine)
    table_type = "f32" if kind == "adjacent" else "bf16"
    table_bytes = 4 if kind == "adjacent" else 2
    arrays = (("input", inputs, "bf16"), ("weight", weights, table_type),
              ("cosine", cosine, table_type), ("sine", sine, table_type),
              ("expected", expected, "bf16"))
    rodata = "\n\n".join(f'global.rodata.def @{name}_{key} = align({4 if dtype == "f32" else 2}) bytes("{encode(values, dtype)}")' for key, values, dtype in arrays)
    initialization = ""
    for key, values, dtype in arrays[:-1]:
        initialization += f'''  %{key}_bytes = index.constant {len(values) * (4 if dtype == "f32" else 2)} : offset
  %{key}_values = global.load @{name}_{key} : buffer
  buffer.copy %{key}_values[%origin], %{key}[%origin], %{key}_bytes
'''
    output = "%input" if shape.inplace else "%output"
    storage = "%input_storage" if shape.inplace else "%output_storage"
    allocation = "" if shape.inplace else f'''    %output_storage = check.generate.fill value(-12345) : tensor<{count + 32}xi16>
    %output = check.tensor.view %output_storage offset(32) : tensor<{count + 32}xi16> -> tensor<{count}xbf16>
'''
    immutable_input = "" if shape.inplace else f"      check.expect.bitwise actual(%input_storage) expected(%input_storage) : tensor<{count + 32}xi16>\n"
    if kind == "half":
        call = "  template.apply<@attention.half_rotary_bf16>(%tokens, %heads, %width, %input, %cosine, %sine, %output) : (index, index, index, buffer, buffer, buffer, buffer)\n"
    else:
        provider = "normalize_rotary_bf16" if kind == "adjacent" else "normalize_half_rotary_bf16"
        call = f"  %epsilon = scalar.constant {literal(epsilon_for(shape, kind))} : f32\n  template.apply<@attention.{provider}>(%tokens, %heads, %width, %epsilon, %input, %weight, %cosine, %sine, %output) : (index, index, index, f32, buffer, buffer, buffer, buffer, buffer)\n"
    return f'''
{rodata}

func.def @initialize_{name}(%input: buffer, %weight: buffer, %cosine: buffer, %sine: buffer) {{
  %origin = index.constant 0 : offset
{initialization}  func.return
}}

kernel.def target(@rotary_rows_wave32) @apply_{name}() {{
  %rows = index.constant {shape.tokens * shape.heads} : index
  %threads = index.constant {shape.width // 2} : index
  %unit = index.constant 1 : index
  kernel.launch.config workgroups(%rows, %unit, %unit) workgroup_size(%threads, %unit, %unit) : index
}} launch(%input: buffer, %weight: buffer, %cosine: buffer, %sine: buffer, %output: buffer) {{
  %tokens = index.constant {shape.tokens} : index
  %heads = index.constant {shape.heads} : index
  %width = index.constant {shape.width} : index
{call}  kernel.return
}}

func.def @reference_{name}(%input: buffer, %weight: buffer, %cosine: buffer, %sine: buffer, %output: buffer) {{
  %origin = index.constant 0 : offset
  %bytes = index.constant {count * 2} : offset
  %values = global.load @{name}_expected : buffer
  buffer.copy %values[%origin], %output[%origin], %bytes
  func.return
}}

check.scenario public @{name} {{
  check.requires<hal.amdgpu.target> {{target = "gfx11-generic"}}
  check.trial[1](%trial: index, %entropy: check.entropy) {{
    %input_storage = check.generate.fill value(-12345) : tensor<{count + 32}xi16>
    %input = check.tensor.view %input_storage offset(32) : tensor<{count + 32}xi16> -> tensor<{count}xbf16>
    %weight_storage = check.generate.fill value(123.0) : tensor<{shape.width + 32}x{table_type}>
    %weight = check.tensor.view %weight_storage offset({16 * table_bytes}) : tensor<{shape.width + 32}x{table_type}> -> tensor<{shape.width}x{table_type}>
    %cosine_storage = check.generate.fill value(123.0) : tensor<{table_count + 32}x{table_type}>
    %cosine = check.tensor.view %cosine_storage offset({16 * table_bytes}) : tensor<{table_count + 32}x{table_type}> -> tensor<{table_count}x{table_type}>
    %sine_storage = check.generate.fill value(123.0) : tensor<{table_count + 32}x{table_type}>
    %sine = check.tensor.view %sine_storage offset({16 * table_bytes}) : tensor<{table_count + 32}x{table_type}> -> tensor<{table_count}x{table_type}>
    check.generate<@initialize_{name}>(%input, %weight, %cosine, %sine) : (tensor<{count}xbf16>, tensor<{shape.width}x{table_type}>, tensor<{table_count}x{table_type}>, tensor<{table_count}x{table_type}>) -> ()
{allocation}    %prefix = check.tensor.view {storage} offset(0) : tensor<{count + 32}xi16> -> tensor<16xi16>
    %suffix = check.tensor.view {storage} offset({count * 2 + 32}) : tensor<{count + 32}xi16> -> tensor<16xi16>
    check.compare<@apply_{name}, @reference_{name}>(%input, %weight, %cosine, %sine, {output}) : (tensor<{count}xbf16>, tensor<{shape.width}x{table_type}>, tensor<{table_count}x{table_type}>, tensor<{table_count}x{table_type}>, tensor<{count}xbf16>) -> () {{
      check.expect.bitwise actual({output}) expected({output}) : tensor<{count}xbf16>
{immutable_input}      check.expect.bitwise actual(%weight_storage) expected(%weight_storage) : tensor<{shape.width + 32}x{table_type}>
      check.expect.bitwise actual(%cosine_storage) expected(%cosine_storage) : tensor<{table_count + 32}x{table_type}>
      check.expect.bitwise actual(%sine_storage) expected(%sine_storage) : tensor<{table_count + 32}x{table_type}>
      check.expect.bitwise actual(%prefix) expected(%prefix) : tensor<16xi16>
      check.expect.bitwise actual(%suffix) expected(%suffix) : tensor<16xi16>
    }}
  }}
  check.return
}}

check.benchmark<@{name}> @{name}_benchmark
'''


def render_rows():
    header = '''// Generated by generate_rotary_oracle.py.
// Whole-array references distinguish pairing, token tables, and tensor rounding.
// Normalized tensors are invariant across the declared inverse error interval.

amdgpu.target<gfx11-generic> @rotary_rows_wave32 {subgroup_size = 32}

template.decl @attention.normalize_rotary_bf16(%tokens: index, %heads: index, %width: index, %epsilon: f32, %input: buffer, %weight: buffer, %cosine: buffer, %sine: buffer, %output: buffer)

template.decl @attention.normalize_half_rotary_bf16(%tokens: index, %heads: index, %width: index, %epsilon: f32, %input: buffer, %weight: buffer, %cosine: buffer, %sine: buffer, %output: buffer)

template.decl @attention.half_rotary_bf16(%tokens: index, %heads: index, %width: index, %input: buffer, %cosine: buffer, %sine: buffer, %output: buffer)
'''
    return header + "".join(render_row(shape, kind) for shape in SHAPES for kind in ("adjacent", "normalized_half", "half"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, render in (("rotary_scalar", render_scalar), ("rotary_rows", render_rows)):
        path = Path(__file__).with_name(name + ".loom")
        content = render()
        if args.check:
            if path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"{path} differs from its independent reference")
        else:
            path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
