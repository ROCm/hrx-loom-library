"""Selects an installed Loom SDK or an HRX source toolchain."""

from __future__ import annotations

import argparse
import json
import shlex
import shutil
import sys
from pathlib import Path
from typing import Any

from ..context import RepositoryContext, UserError


def _write_source_override(context: RepositoryContext, source_path: str) -> None:
    source_root = Path(source_path).expanduser()
    if not source_root.is_absolute():
        source_root = context.repository_root / source_root
    source_root = source_root.resolve()
    if not (source_root / "MODULE.bazel").is_file():
        raise UserError(f"HRX source module has no MODULE.bazel: {source_root}")
    override_argument = f"--override_module=hrx={source_root.as_posix()}"
    contents = (
        "# Generated by dev.py setup --hrx-source.\n"
        f"common {shlex.quote(override_argument)}\n"
        "common --repo_env=LOOM_SDK_PYTHON=\n"
    )
    source_bazelrc = context.repository_root / ".bazelrc.hrx"
    if (
        source_bazelrc.exists()
        and source_bazelrc.read_text(encoding="utf-8") == contents
    ):
        print(f"Local HRX source already selected: {source_root}", flush=True)
        return
    source_bazelrc.write_text(contents, encoding="utf-8")
    print(f"Selected local HRX source: {source_root}", flush=True)


def _select_pinned_source(context: RepositoryContext) -> None:
    source_bazelrc = context.repository_root / ".bazelrc.hrx"
    source_bazelrc.write_text(
        "# Generated by dev.py setup --pinned-source.\n"
        "common --repo_env=LOOM_SDK_PYTHON=\n",
        encoding="utf-8",
    )
    print("Selected the HRX source revision pinned by MODULE.bazel", flush=True)


def _write_sdk_override(context: RepositoryContext, python: str) -> None:
    executable = shutil.which(python)
    if executable is None:
        raise UserError(f"Python interpreter is not executable: {python}")
    # Resolving a venv's Python symlink would select the base environment.
    executable = str(Path(executable).absolute())
    probe = context.repository_root / "build_tools/bazel/sdk_probe.py"
    sdk = json.loads(context.run([executable, "-B", str(probe)], capture_output=True))
    argument = f"--repo_env=LOOM_SDK_PYTHON={Path(executable).as_posix()}"
    # Pure Python rules attempt optional C++ toolchain discovery. SDK mode has
    # no native build actions and must also work on hosts without a C++ compiler.
    (context.repository_root / ".bazelrc.hrx").write_text(
        f"# Generated by dev.py setup --sdk.\ncommon {shlex.quote(argument)}\n"
        "common --repo_env=BAZEL_DO_NOT_DETECT_CPP_TOOLCHAIN=1\n",
        encoding="utf-8",
    )
    print(f"Selected installed hrx-loom {sdk['version']} from {executable}", flush=True)


def _run(args: argparse.Namespace, context: RepositoryContext) -> None:
    if args.hrx_source:
        _write_source_override(context, args.hrx_source)
    elif args.pinned_source:
        _select_pinned_source(context)
    else:
        _write_sdk_override(context, args.sdk or sys.executable)
    context.bazel(["build", "--nobuild", "--lockfile_mode=update", "//..."])


def register(subparsers: Any) -> None:
    parser = subparsers.add_parser(
        "setup",
        help="Select an installed SDK (default) or an HRX source tree.",
        description=__doc__,
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--hrx-source",
        metavar="PATH",
        help="Use an uncommitted local HRX checkout as the hrx module.",
    )
    mode.add_argument(
        "--sdk",
        nargs="?",
        const=sys.executable,
        metavar="PYTHON",
        help="Use hrx-loom installed in this Python environment (or PYTHON).",
    )
    mode.add_argument(
        "--pinned-source",
        action="store_true",
        help="Build tools from the HRX source revision pinned by MODULE.bazel.",
    )
    parser.set_defaults(handler=_run)
