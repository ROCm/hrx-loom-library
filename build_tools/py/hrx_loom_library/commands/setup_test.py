from __future__ import annotations

import argparse
import shlex
import tempfile
import unittest
from pathlib import Path

from build_tools.py.hrx_loom_library.commands import setup
from build_tools.py.hrx_loom_library.context import RepositoryContext


class SetupCommandTest(unittest.TestCase):
    def _parser(self) -> argparse.ArgumentParser:
        parser = argparse.ArgumentParser()
        subparsers = parser.add_subparsers(dest="command", required=True)
        setup.register(subparsers)
        return parser

    def test_parser_names_the_overridden_hrx_module(self):
        args = self._parser().parse_args(
            ["setup", "--hrx-source=/worktrees/hrx-system"]
        )

        self.assertEqual(args.hrx_source, "/worktrees/hrx-system")
        self.assertFalse(hasattr(args, "loom_source"))

    def test_local_source_override_selects_the_hrx_module(self):
        with tempfile.TemporaryDirectory() as temporary_directory:
            repository_root = Path(temporary_directory) / "library"
            source_root = Path(temporary_directory) / "hrx-system"
            repository_root.mkdir()
            source_root.mkdir()
            (source_root / "MODULE.bazel").write_text(
                'module(name = "hrx")\n', encoding="utf-8"
            )
            context = RepositoryContext(repository_root)
            local_settings = repository_root / ".bazelrc.local"
            local_settings.write_text("build --jobs=7\n", encoding="utf-8")

            setup._write_source_override(context, str(source_root))

            override = f"--override_module=hrx={source_root.as_posix()}"
            self.assertEqual(
                (repository_root / ".bazelrc.hrx").read_text(encoding="utf-8"),
                "# Generated by dev.py setup --hrx-source.\n"
                f"common {shlex.quote(override)}\n",
            )

            self.assertEqual(local_settings.read_text(), "build --jobs=7\n")
            setup._select_release(context)
            self.assertFalse((repository_root / ".bazelrc.hrx").exists())
            self.assertEqual(local_settings.read_text(), "build --jobs=7\n")


if __name__ == "__main__":
    unittest.main()
