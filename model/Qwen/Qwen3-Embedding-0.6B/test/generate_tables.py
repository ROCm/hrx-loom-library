"""Check or regenerate program-owned SiLU/rotary constants without model data.

This developer tool derives mathematical constants using only the standard
library. Model acquisition and serving never invoke it or require Python math
packages. Binary32 round points follow the publisher's rotary expression;
the stored BF16 values use round-to-nearest, ties-to-even.
"""

import argparse
import math
from pathlib import Path
import struct


def binary32(value: float) -> float:
    return struct.unpack("<f", struct.pack("<f", value))[0]


def bfloat16(value: float) -> int:
    bits = struct.unpack("<I", struct.pack("<f", value))[0]
    return ((bits + 0x7FFF + ((bits >> 16) & 1)) >> 16) & 0xFFFF


def table_bytes() -> bytes:
    silu = [0] * 4096
    for position, bits in enumerate(range(0x3B80, 0x4301)):
        value = struct.unpack("<f", struct.pack("<I", bits << 16))[0]
        exponential = math.exp(-value)
        silu[position] = bfloat16(value / (1 + exponential))
        silu[2048 + position] = bfloat16(-value * exponential / (1 + exponential))
    frequencies = [
        binary32(1 / binary32(math.pow(1000000, binary32(2 * position / 128))))
        for position in range(64)
    ]
    rotary = []
    for position in range(128):
        angles = [binary32(float(position) * frequency) for frequency in frequencies]
        rotary.extend(bfloat16(binary32(math.cos(angle))) for angle in angles)
        rotary.extend(bfloat16(binary32(math.sin(angle))) for angle in angles)
    return struct.pack("<4096H", *silu) + struct.pack("<16384H", *rotary)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    source = args.source.read_text()
    begin = source.index("// BEGIN MATHEMATICAL TABLES")
    end_marker = "// END MATHEMATICAL TABLES"
    end = source.index(end_marker, begin) + len(end_marker)
    generated = (
        "// BEGIN MATHEMATICAL TABLES\n"
        "// BF16 SiLU and rotary values; regenerated by test/generate_tables.py.\n"
        'global.rodata.def @qwen3_embedding.math_tables = align(64) bytes("'
        + table_bytes().hex()
        + '")\n\n'
        + end_marker
    )
    if args.write:
        args.source.write_text(source[:begin] + generated + source[end:])
    elif source[begin:end] != generated:
        raise SystemExit("Program constants differ from the SiLU/rotary expressions")


if __name__ == "__main__":
    main()
